#[enum_fn(#[doc = "Returns the protocol code."] #[inline] code -> u8)]
#[doc = "A state with a documented generated accessor."]
enum DocumentedAccessor {
    Ready = 200,
}

#[test]
fn treats_numeric_and_named_values_as_expressions() {
    const VALUE: &NumericDescription = &NumericDescription::Dynamic(String::new());
    const DYNAMIC: u8 = VALUE.description();
    assert_eq!(NumericDescription::Tuple.description(), 1);
    assert_eq!(NumericDescription::Struct.description(), 2);
    let dynamic = NumericDescription::Dynamic(String::from("payload"));
    assert_eq!(dynamic.description(), 0);
    assert_eq!(DYNAMIC, 0);
    assert!(matches!(dynamic, NumericDescription::Dynamic(value) if value == "payload"));
    let pair = NumericDescription::Pair(4, 5);
    assert_eq!(pair.description(), 9);
    assert!(matches!(pair, NumericDescription::Pair(4, 5)));
    let named = NamedConstant::Value { CONST_SCORE: 99 };
    assert_eq!(named.score(), CONST_SCORE);
    assert!(matches!(named, NamedConstant::Value { CONST_SCORE: 99 }));
    assert_eq!(RuntimeExpression::Computed.score(), 7);
    assert_eq!(DocumentedAccessor::Ready.code(), 200);
}

